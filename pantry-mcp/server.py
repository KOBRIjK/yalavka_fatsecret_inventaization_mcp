mcp = FastMCP('pantry', instructions=INSTRUCTIONS, host=os.environ.get('MCP_HOST', '127.0.0.1'), port=int(os.environ.get('MCP_PORT', '8002')), stateless_http=True)


def now():
    return datetime.now(timezone.utc).isoformat()


def amount(value):
    try:
        n = Decimal(str(value))
    except InvalidOperation:
        raise ValueError('Некорректное количество')
    if not n.is_finite() or n < 0 or n > Decimal('1000000000') or n.as_tuple().exponent < -6:
        raise ValueError('Количество: от 0 до 1 млрд, не более 6 знаков после запятой')
    return format(n, 'f')


@contextmanager
def connect(write=False, snapshot=False):
    if not DATABASE_URL:
        raise RuntimeError('EDA_DATABASE_URL is required; start with Docker Compose')
    with psycopg.connect(DATABASE_URL, row_factory=dict_row) as c:
        if snapshot:
            c.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY')
        c.execute(sql.SQL('SET LOCAL search_path TO {}').format(sql.Identifier(SCHEMA)))
        c.execute("SET LOCAL lock_timeout = '30s'")
        if write:
            # One transaction lock protects retries, multi-item updates and corrections.
            c.execute('SELECT pg_advisory_xact_lock(734216089)')
        yield c


def initialize():
    with connect(True) as c:
        c.execute('CREATE TABLE IF NOT EXISTS connector_state (key TEXT PRIMARY KEY, value JSONB NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now())')
        c.execute('CREATE TABLE IF NOT EXISTS stock (id TEXT PRIMARY KEY, name TEXT NOT NULL, quantity TEXT CHECK (quantity IS NULL OR quantity::numeric >= 0), unit TEXT NOT NULL, location TEXT NOT NULL, expires_on TEXT, note TEXT NOT NULL, external_ids TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 1, updated_at TEXT NOT NULL)')
        c.execute('CREATE TABLE IF NOT EXISTS operations (key TEXT PRIMARY KEY, fingerprint TEXT NOT NULL, result TEXT NOT NULL, created_at TEXT NOT NULL)')
        c.execute('CREATE TABLE IF NOT EXISTS events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, operation_key TEXT NOT NULL REFERENCES operations(key), stock_id TEXT NOT NULL REFERENCES stock(id), action TEXT NOT NULL, before_quantity TEXT, after_quantity TEXT, reason TEXT NOT NULL, created_at TEXT NOT NULL)')


class StockInput(BaseModel):
    name: str = Field(min_length=1, max_length=200)
    quantity: str | None = Field(default=None, description='Число строкой, например 150.5; null = остаток неизвестен')
    unit: Literal['g', 'ml', 'pcs', 'pack']
    location: str = Field(default='не уточнено', max_length=200)
    expires_on: str | None = Field(default=None, description='YYYY-MM-DD, только если известен')
    note: str = Field(default='', max_length=2000)
    external_ids: dict[str, str] = Field(default_factory=dict, description='Например lavka_product_id, fatsecret_food_id')


class StockChange(BaseModel):
    stock_id: str
    action: Literal['add', 'consume', 'discard', 'set']
    quantity: str = Field(description='В единицах выбранной партии; set задаёт абсолютный остаток')
    expected_revision: int | None = Field(default=None, description='Обязательно для set; получить через list_stock')


def transaction(key, payload, apply):
    if not key.strip() or len(key) > 300:
        raise ValueError('Нужен непустой уникальный operation_key длиной до 300 символов')
    serialized = json.dumps(payload, sort_keys=True, ensure_ascii=False)
    fingerprint = hashlib.sha256(serialized.encode()).hexdigest()
    with connect(True) as c:
        previous = c.execute('SELECT * FROM operations WHERE key=%s', (key,)).fetchone()
        if previous:
            if previous['fingerprint'] != fingerprint:
                raise ValueError('Этот operation_key уже использован с другими данными. Проверьте журнал.')
            return {**json.loads(previous['result']), 'already_applied': True}
        c.execute('INSERT INTO operations VALUES (%s, %s, %s, %s)', (key, fingerprint, '{}', now()))
        result = {'already_applied': False, 'operation_key': key, 'items': apply(c)}
        c.execute('UPDATE operations SET result=%s WHERE key=%s', (json.dumps(result, ensure_ascii=False), key))
        return result


def row_dict(row):
    d = dict(row)
    d['external_ids'] = json.loads(d['external_ids'])
    return d


@mcp.tool()
def pantry_status() -> dict:
    """Проверить общее хранилище и наличие данных перед учётом домашних продуктов."""
    with connect() as c:
        count = c.execute('SELECT COUNT(*) AS count FROM stock').fetchone()['count']
        unknown = c.execute('SELECT COUNT(*) AS count FROM stock WHERE quantity IS NULL').fetchone()['count']
        return {'database': 'PostgreSQL', 'stock_batches': count, 'unknown_quantities': unknown,
                'initial_inventory_needed': count == 0, 'automatic_sync': False,
                'units': {'g': 'граммы', 'ml': 'миллилитры', 'pcs': 'штуки', 'pack': 'упаковки'},
                'note': 'Наличие записей не означает, что все запасы дома уже перечислены.'}


@mcp.tool()
def list_stock(query: str = '', include_empty: bool = False) -> dict:
    """Остатки по партиям: ID, количество (null = неизвестно), единицы, срок и revision. Поиск без учёта регистра, включая русский."""
    with connect() as c:
        rows = c.execute('SELECT * FROM stock ORDER BY expires_on IS NULL, expires_on, name, id').fetchall()
        items = [row_dict(r) for r in rows if (include_empty or r['quantity'] is None or Decimal(r['quantity']) > 0)
                 and query.casefold() in (r['name'] + ' ' + r['location']).casefold()]
        return {'items': items, 'count': len(items)}


@mcp.tool()
def receive_stock(items: list[StockInput], operation_key: str, reason: str) -> dict:
    """Добавить начальные запасы или полученную покупку отдельными партиями. Атомарно, с защитой от повторов. Один заказ = один вызов и ключ lavka:order:<id>. quantity=null если остаток неизвестен. Не предполагает, что инвентаризация завершена."""
    if not 1 <= len(items) <= 500 or not reason.strip():
        raise ValueError('Нужны от 1 до 500 позиций и причина')
    for item in items:
        if not item.name.strip():
            raise ValueError('Название не должно быть пустым')
        if item.quantity is not None:
            amount(item.quantity)
        if item.expires_on:
            date.fromisoformat(item.expires_on)
    def apply(c):
        result = []
        for item in items:
            stock_id = str(uuid4())
            qty = None if item.quantity is None else amount(item.quantity)
            c.execute('INSERT INTO stock VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)',
                      (stock_id, item.name.strip(), qty, item.unit, item.location, item.expires_on,
                       item.note, json.dumps(item.external_ids), 1, now()))
            c.execute('INSERT INTO events(operation_key,stock_id,action,before_quantity,after_quantity,reason,created_at) VALUES(%s,%s,%s,%s,%s,%s,%s)',
                      (operation_key, stock_id, 'receive', None, qty, reason, now()))
            result.append(row_dict(c.execute('SELECT * FROM stock WHERE id=%s', (stock_id,)).fetchone()))
        return result
    return transaction(operation_key, {'kind': 'receive', 'items': [i.model_dump() for i in items], 'reason': reason}, apply)


@mcp.tool()
def change_stock(changes: list[StockChange], operation_key: str, reason: str) -> dict:
    """Списать съеденное/выброшенное, добавить к партии или исправить остаток. Атомарно: при ошибке не меняется ничего. Не допускает отрицательный остаток. set требует expected_revision; неизвестный остаток сначала сверить через set. Количества только в единицах партии."""
    if not 1 <= len(changes) <= 500 or not reason.strip():
        raise ValueError('Нужны от 1 до 500 изменений и причина')
    if len({i.stock_id for i in changes}) != len(changes):
        raise ValueError('Одна партия может встречаться в вызове только один раз')
    def apply(c):
        result = []
        for change in changes:
            row = c.execute('SELECT * FROM stock WHERE id=%s', (change.stock_id,)).fetchone()
            if row is None:
                raise ValueError('Партия не найдена: ' + change.stock_id)
            if change.action == 'set' and change.expected_revision is None:
                raise ValueError('Для set обязательна expected_revision из list_stock')
            if change.expected_revision is not None and row['revision'] != change.expected_revision:
                raise ValueError('Остаток уже изменился. Перечитайте list_stock.')
            qty = Decimal(amount(change.quantity))
            before = row['quantity']
            if change.action == 'set':
                after = qty
            else:
                if before is None:
                    raise ValueError('Остаток неизвестен: сначала сверьте и задайте set')
                after = Decimal(before) + (qty if change.action == 'add' else -qty)
            after_text = amount(after)
            c.execute('UPDATE stock SET quantity=%s,revision=revision+1,updated_at=%s WHERE id=%s', (after_text, now(), change.stock_id))
            c.execute('INSERT INTO events(operation_key,stock_id,action,before_quantity,after_quantity,reason,created_at) VALUES(%s,%s,%s,%s,%s,%s,%s)',
                      (operation_key, change.stock_id, change.action, before, after_text, reason, now()))
            result.append(row_dict(c.execute('SELECT * FROM stock WHERE id=%s', (change.stock_id,)).fetchone()))
        return result
    return transaction(operation_key, {'kind': 'change', 'changes': [i.model_dump() for i in changes], 'reason': reason}, apply)


@mcp.tool()
def stock_history(stock_id: str | None = None, limit: int = 50, before_event_id: int | None = None) -> dict:
    """Журнал покупок, списаний и исправлений. Пагинация: передайте next_before_event_id."""
    if not 1 <= limit <= 500:
        raise ValueError('limit должен быть от 1 до 500')
    with connect() as c:
        rows = c.execute('SELECT e.*,s.name,s.unit FROM events e JOIN stock s ON s.id=e.stock_id WHERE (%s::text IS NULL OR e.stock_id=%s) AND (%s::bigint IS NULL OR e.id<%s) ORDER BY e.id DESC LIMIT %s',
                         (stock_id, stock_id, before_event_id, before_event_id, limit)).fetchall()
        return {'events': [dict(r) for r in rows], 'next_before_event_id': rows[-1]['id'] if len(rows) == limit else None}


@mcp.tool()
def backup_pantry() -> dict:
    """Сохранить согласованную JSON-копию запасов, операций и журнала в /backups. Полный PostgreSQL сохраняется через pg_dump."""
    folder = Path(os.environ.get('PANTRY_BACKUP_DIR', '/backups'))
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / (datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S') + '-' + uuid4().hex[:8] + '.json')
    with connect(snapshot=True) as c:
        payload = {'format': 'pantry-postgres-v1', 'created_at': now()}
        for table in ('stock', 'operations', 'events'):
            payload[table] = c.execute(sql.SQL('SELECT * FROM {}').format(sql.Identifier(table))).fetchall()
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding='utf-8')
    return {'backup': str(path)}


